def agree_fig(w=9.6, h=5.6):
    fig, ax = plt.subplots(figsize=(w, h), dpi=100); n = len(RECS)
    for i, (k, v) in enumerate(RECS):
        y = n - 1 - i; c = '#1F5F8B' if v >= 95 else ('#2E8B57' if v >= 90 else '#E3A21A')
        ax.barh(y, v - 80, .66, left=80, color=c); ax.text(v + .3, y, f'{v:g}%', va='center', fontsize=16)
    ax.set_yticks(range(n), [r[0] for r in RECS][::-1], fontsize=17); ax.set_xlim(80, 103); ax.tick_params(axis='x', labelsize=12)
    for x, t in [(85, '基本共识 ≥85%'), (90, '普遍共识 ≥90%'), (95, '高度共识 ≥95%')]:
        ax.axvline(x, color='#bbb', lw=1, ls='--'); ax.text(x + .2, n - .1, t, fontsize=13, color='#666')
    ax.set_ylim(-.6, n + 1.2); ax.spines[['top', 'right']].set_visible(False); fig.tight_layout(); return fig


