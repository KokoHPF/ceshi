def timeline_fig(w=9.6, h=5.2):
    """围手术期 MCVT 管理时间轴（编者据原文推荐意见 2、8～10、14～19 绘制）"""
    ev = [('骨折→术后 4 周', '围手术期 MCVT 诊断窗', '#1F5F8B'), ('确诊后', '按高危因素决定是否抗凝', '#1F5F8B'), ('抗凝 10～14 天', '复查，评估滤器指征', '#1F5F8B'),
          ('术后', 'ERAS 早期下地', '#E3A21A'), ('术后 0～2 周', '每周复查超声', '#E3A21A'), ('血栓稳定 3～4 周', '考虑压力疗法', '#2E8B57'),
          ('抗凝 6 周', '复查超声', '#2E8B57'), ('3 个月 · 6 个月', '关键评估 · 高危延长随访', '#2E8B57')]
    fig, ax = plt.subplots(figsize=(w, h), dpi=100); ax.set_xlim(0, 2); ax.set_ylim(-.2, 5.2); ax.axis('off')
    for i, (t, s_, c) in enumerate(ev):
        col, row = divmod(i, 4); x = .04 + col * 1.0; y = 3.75 - row * 1.15
        ax.scatter(x + .05, y, s=300, color=c, edgecolors='white', linewidths=2.5, zorder=2)
        ax.text(x + .12, y + .2, t, ha='left', va='center', fontsize=19, color=c, weight='bold')
        ax.text(x + .12, y - .25, s_, ha='left', va='center', fontsize=17, color='#222')
    fig.tight_layout(pad=.2); return fig


def course_fig(w=9.6, h=5.6):
    """IDDVT 抗凝疗程 RCT 结果（据原文数字绘制）"""
    fig, ax = plt.subplots(figsize=(w, h), dpi=100)
    grp = [('RCT 1：VTE 复发', [('6 周', 2.0), ('12 周', 3.4)]), ('RCT 1：大出血', [('6 周', 1.0), ('12 周', 3.4)]), ('RCT 2：2 年 VTE 复发', [('6 周', 19), ('3 个月', 11)])]
    col = ['#E3A21A', '#1F5F8B']; x0 = 0
    for g, (name, bars) in enumerate(grp):
        for j, (lab, v) in enumerate(bars):
            x = g * 2.6 + j; ax.bar(x, v, .8, color=col[j])
            ax.text(x, v + .4, (f'{v:.1f}%' if v < 10 else f'{v:g}%'), ha='center', fontsize=19, weight='bold', color=col[j]); ax.text(x, -1.4, lab, ha='center', fontsize=16)
        ax.text(g * 2.6 + .5, -3.2, name, ha='center', fontsize=16, color='#444')
    ax.text(.5, 6.5, '差异无统计学意义', ha='center', fontsize=14, color='#888'); ax.text(3.1, 6.5, '差异无统计学意义', ha='center', fontsize=14, color='#888')
    ax.text(5.7, 21.5, 'RR 0.59（95% CI 0.36～0.95）', ha='center', fontsize=14, color='#888')
    ax.set_xlim(-.7, 6.9); ax.set_ylim(-4, 24); ax.axis('off'); fig.tight_layout(); return fig


def fig2img(fig):
    buf = BytesIO(); fig.savefig(buf, format='png', dpi=100, facecolor='white'); plt.close(fig); return Image.open(buf).convert('RGB')


