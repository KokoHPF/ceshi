def block(text, size, color, align):
    """把多行中文排成一块透明图层"""
    f = font(size); lh = int(size * 1.18)
    ls = text.split('\n'); d0 = ImageDraw.Draw(Image.new('RGB', (1, 1)))
    w = int(max(d0.textlength(l, font=f) for l in ls)) + 4
    lay = Image.new('RGBA', (w, lh * len(ls) + 4), (0, 0, 0, 0)); d = ImageDraw.Draw(lay)
    for i, l in enumerate(ls):
        tw = d.textlength(l, font=f)
        x = {'l': 2, 'r': w - tw - 2, 'c': (w - tw) / 2}[align]
        d.text((x, 2 + i * lh), l, font=f, fill=color)
    return lay


def badge(im, t):
    d = ImageDraw.Draw(im); f = font(max(26, im.width // 30))
    w = d.textlength(t, font=f) + 24; h = f.size + 16
    x = im.width - w - 10; y = im.height - h - 10
    d.rounded_rectangle([x, y, x + w, y + h], 8, fill=RED)
    d.text((x + 12, y + 7), t, font=f, fill='white')
    return im


