def comp_fig(w=9.6, h=5.2, cover=False):
    """不同康复模式的总并发症发生率（Mortada 等 meta 分析，据原文数字绘制）"""
    fig, ax = plt.subplots(figsize=(w, h), dpi=100)
    lab = ['早期被动活动', '早期主动活动', '制动']; v = [5.5, 15.7, 27.8]; c = ['#2E8B57', '#E3A21A', '#C0392B']
    ax.bar(range(3), v, .58, color=c)
    for i, x in enumerate(v): ax.text(i, x + .8, f'{x}%', ha='center', fontsize=22, weight='bold', color=c[i])
    ax.set_xticks(range(3), lab, fontsize=19); ax.set_ylim(0, 36 if not cover else 40); ax.set_yticks([])
    ax.spines[['top', 'right', 'left']].set_visible(False)
    if not cover: ax.set_title('总并发症发生率（Mortada 等 meta 分析）', fontsize=17, pad=8)
    fig.tight_layout(); return fig


def fig2img(fig):
    buf = BytesIO(); fig.savefig(buf, format='png', dpi=100, facecolor='white'); plt.close(fig); return Image.open(buf).convert('RGB')


