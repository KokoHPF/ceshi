def flow_img(w=9.6, h=6.4):
    """9 个环节 × 15 条推荐的流程示意（编者据原文表 3 绘制）"""
    fig, ax = plt.subplots(figsize=(w, h), dpi=100); ax.set_xlim(0, 10); ax.set_ylim(-.5, 7.5); ax.axis('off')
    groups = [('诊断', [1]), ('术前评估', [2, 3]), ('术前宣教', [4]), ('手术时机', [5]), ('麻醉策略', [6]),
              ('稳定性重建', [7, 8]), ('常规管理', [9, 10, 11, 12]), ('并发症预防', [13, 14]), ('术后康复', [15])]
    st = {s[1]: s[2] for s in STEPS}
    for i, (g, recs) in enumerate(groups):
        r, c = divmod(i, 3); x = .25 + c * 3.25; y = 4.95 - r * 2.15
        ax.add_patch(FancyBboxPatch((x, y), 3.0, 1.75, boxstyle='round,pad=0.02,rounding_size=0.18', fc='#F2F6FA', ec='#C9D6E3', lw=1.5))
        ax.text(x + 1.5, y + 1.3, f'{i + 1}  {g}', ha='center', va='center', fontsize=19, color='#16324F', weight='bold')
        n = len(recs); bw = min(.62, 2.7 / n - .08); x0 = x + 1.5 - (n * bw + (n - 1) * .08) / 2
        for j, rr in enumerate(recs):
            xx = x0 + j * (bw + .08)
            ax.add_patch(FancyBboxPatch((xx, y + .22), bw, .62, boxstyle='round,pad=0.01,rounding_size=0.1', fc=COL[st[rr]], ec='none'))
            ax.text(xx + bw / 2, y + .53, str(rr), ha='center', va='center', fontsize=17, color='white', weight='bold')
    for j, (lab, key) in enumerate([('强推荐 9 条', '强'), ('弱推荐 5 条', '弱'), ('专家建议 1 条', 'GPS')]):
        ax.add_patch(FancyBboxPatch((.4 + j * 3.2, -.42), .35, .3, boxstyle='round,pad=0.01,rounding_size=0.06', fc=COL[key], ec='none'))
        ax.text(.9 + j * 3.2, -.27, lab, va='center', fontsize=16, color='#333')
    fig.tight_layout(pad=.3); return fig


def fig2img(fig):
    buf = BytesIO(); fig.savefig(buf, format='png', dpi=100, facecolor='white'); plt.close(fig); return Image.open(buf).convert('RGB')


