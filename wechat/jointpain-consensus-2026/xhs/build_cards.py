def ladder_fig(w=9.6, h=5.2):
    """阶梯化管理（编者据原文 4 节绘制）"""
    fig, ax = plt.subplots(figsize=(w, h), dpi=100); ax.set_xlim(0, 10); ax.set_ylim(0, 5.4); ax.axis('off')
    st = [('非药物治疗', '教育 · 运动 · 理疗 · 辅具', '#2E8B57'), ('药物治疗', '外用 → 口服', '#E3A21A'), ('介入 / 外科', '注射 · 射频 · 手术', '#C0392B')]
    for i, (t, s_, c) in enumerate(st):
        x = .2 + i * 3.3; y = 2.9 - i * 1.15
        ax.add_patch(FancyBboxPatch((x, y), 3.0, 1.3, boxstyle='round,pad=0.02,rounding_size=0.18', fc=c, ec='none'))
        ax.text(x + 1.5, y + .88, t, ha='center', va='center', fontsize=23, color='white', weight='bold')
        ax.text(x + 1.5, y + .38, s_, ha='center', va='center', fontsize=15, color='white')
        if i < 2: ax.annotate('', (x + 3.3, y - .45), (x + 2.6, y + .1), arrowprops=dict(arrowstyle='-|>', lw=3, color='#777'))
    ax.text(.25, .9, '口服镇痛：非阿片类 → 弱阿片类 → 强阿片类', fontsize=18, color='#1F5F8B', weight='bold')
    ax.text(.25, .25, '个体化 · 阶梯化 · 综合性', fontsize=16, color='#555')
    fig.tight_layout(pad=.2); return fig


def fig2img(fig):
    buf = BytesIO(); fig.savefig(buf, format='png', dpi=100, facecolor='white'); plt.close(fig); return Image.open(buf).convert('RGB')


