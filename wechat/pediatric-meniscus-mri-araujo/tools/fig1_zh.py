def main(src, dst, font="/usr/share/fonts/truetype/wqy/wqy-zenhei.ttc"):
    img = cv2.imread(src)
    gray = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
    mask = np.zeros(gray.shape, np.uint8)
    for (x0, y0, x1, y1), *_ in LABELS:
        x0, y0, x1, y1 = x0 - 3, y0 - 3, x1 + 3, y1 + 3
        roi = gray[y0:y1, x0:x1]
        # 文字比周围亮：取框内高于局部中位数一截的像素当文字
        thr = max(np.median(roi) + 45, 110)
        m = (roi > thr).astype(np.uint8) * 255
        mask[y0:y1, x0:x1] |= cv2.dilate(m, np.ones((5, 5), np.uint8))
    img = cv2.inpaint(img, mask, 5, cv2.INPAINT_TELEA)

    im = Image.fromarray(cv2.cvtColor(img, cv2.COLOR_BGR2RGB))
    d = ImageDraw.Draw(im)
    for (x0, y0, x1, y1), text, align, size in LABELS:
        if not text:
            continue
        f = ImageFont.truetype(font, size)
        lines = text.split("\n")
        lh = size + 2
        top = (y0 + y1) / 2 - lh * len(lines) / 2
        for i, ln in enumerate(lines):
            w = d.textlength(ln, font=f)
            x = {"l": x0, "c": (x0 + x1) / 2 - w / 2, "r": x1 - w}[align]
            d.text((x, top + i * lh), ln, font=f, fill="white", stroke_width=2, stroke_fill=(20, 20, 20))
    im.save(dst)


if __name__ == "__main__":
    main(*sys.argv[1:])
