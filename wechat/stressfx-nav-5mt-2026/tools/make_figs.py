# ---------- 在原图编号旁加中文名称（半透明深色小框，尽量不挡结构） ----------
def labels(name, items, fs, legend=None, out=None):
    """items: (x, y, 文字, 锚点)，锚点 l=文字在点右侧、r=在点左侧、c=以点为中心；坐标为原图像素。
    legend: (x, y, [行]) 写在原图黑底空白处的图例。"""
    im = (k.op(name) if isinstance(name, str) else name).convert('RGBA'); ov = Image.new('RGBA', im.size, (0, 0, 0, 0)); d = ImageDraw.Draw(ov); f = FB(fs)
    pad = round(fs * .3)
    for x, y, t, a in items:
        w = d.textlength(t, font=f); x0 = {'l': x, 'r': x - w - 2 * pad, 'c': x - w / 2 - pad}[a]; y0 = y - fs / 2 - pad
        d.rounded_rectangle([x0, y0, x0 + w + 2 * pad, y0 + fs + 2 * pad], pad, fill=(15, 30, 45, 190))
        d.text((x0 + pad, y0 + pad + fs * .45), t, font=f, fill=(255, 236, 140, 255), anchor='lm')
    if legend:
        lx, ly, rows = legend
        items = list(items) + [(lx, ly + fs / 2 + pad + i * (fs + 2 * pad + 6), t, 'l') for i, t in enumerate(rows)]
    for x, y, t, a in items[len(items) - len(legend[2]):] if legend else []:
        w = d.textlength(t, font=f); y0 = y - fs / 2 - pad
        d.rounded_rectangle([x, y0, x + w + 2 * pad, y0 + fs + 2 * pad], pad, fill=(15, 30, 45, 190))
        d.text((x + pad, y0 + pad + fs * .45), t, font=f, fill=(255, 236, 140, 255), anchor='lm')
    im = Image.alpha_composite(im, ov).convert('RGB')
    if out: im.save(f'{WORK}/{out}.jpg', quality=92)
    return im


