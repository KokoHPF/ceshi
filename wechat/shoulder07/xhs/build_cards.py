ROWS = {'x73': [(0, 474), (515, 983)], 'x95': [(0, 442), (500, 946)]}
def P(x, k):
    """第 k 个面板（a=0），按原图切分，不改动像素"""
    im = Image.open(os.path.join(WORK, f'{x}.jpg')).convert('RGB'); cols = COLS[x]; rows = ROWS.get(x, [(0, im.height)])
    r, c = divmod(k, len(cols)); (x0, x1), (y0, y1) = cols[c], rows[r]; return im.crop((x0, y0, x1, y1))
L = lambda s: 'abcdefgh'.index(s)
Y, R = '**黄箭头**', '**红箭头**'
def grid(*ims, gap=10):
    """原图面板按 2 列排成网格（每行等高缩放，不改动内容），让多格图在竖版卡片上更大"""
    rows = [ims[i:i + 2] for i in range(0, len(ims), 2)]; W = 1400; out = []
    for r in rows:
        h = round((W - gap * (len(r) - 1)) / sum(i.width / i.height for i in r)) if len(r) > 1 else round(min(W / 2 * 1.4, r[0].height * 1.6) )
        rr = [i.resize((round(i.width * h / i.height), h), Image.LANCZOS) for i in r]; out.append(rr)
    H = sum(r[0].height for r in out) + gap * (len(out) - 1); c = Image.new('RGB', (W, H), 'white'); y = 0
    for r in out:
        x = (W - sum(i.width for i in r) - gap * (len(r) - 1)) // 2
        for i in r: c.paste(i, (x, y)); x += i.width + gap
        y += r[0].height + gap
    return c

